# contar de 1 a 10
i = 1 # inicialização
while i <= 10: # condição de fim
    print(i) # o comando a ser repetido
    i = i + 1 # passo ou contagem

print ("========")

# for i in range (inicialização , condição de fim + 1, passo)
for i in range (1, 11, 1):
    print(i)

print ("========")

for i in range (1, 11):
    print(i)

print ("========")

for i in range (10):
    print (i)

print ("========")

for i in range (1, 11, 2):
    print (i)

print ("========")

for i in range (10, 0, -1):
    print (i)
    
